// Package nginxctl manages the include file holding the upstream (load balancer)
// of each HTTP service: exactly one file per service, never touching the main
// vhost/server block of nginx. The vhost must `include` this file beforehand (see
// deploy/nginx/*.example) so the agent cannot break unrelated nginx configuration.
package nginxctl

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type Client struct {
	UpstreamPath string
	// UpstreamName is the name vhosts reference in proxy_pass.
	UpstreamName string
	// StickySessions emits ip_hash, for apps whose long-lived streams (SSE) keep
	// per-process state.
	StickySessions bool
	TestCmd        string
	ReloadCmd      string
}

// Render builds the upstream file content from the list of running ports.
func Render(name string, stickySessions bool, ports []int) string {
	var b strings.Builder
	b.WriteString("# This file is generated by deploy-agent and overwritten on every deploy. Do not edit by hand.\n")
	fmt.Fprintf(&b, "upstream %s {\n", name)
	if stickySessions {
		b.WriteString("    # Long-lived streams (e.g. SSE) and the requests tied to them must hit the same instance because the app keeps per-process state.\n")
		b.WriteString("    ip_hash;\n")
	}
	for _, p := range ports {
		fmt.Fprintf(&b, "    server 127.0.0.1:%d;\n", p)
	}
	b.WriteString("}\n")
	return b.String()
}

func runShell(ctx context.Context, cmdline string) (string, error) {
	cmd := exec.CommandContext(ctx, "sh", "-c", cmdline)
	out, err := cmd.CombinedOutput()
	return string(out), err
}

// WriteAndApply writes the new upstream file, validates it with `nginx -t` and
// reloads if it passes. If the test fails, it restores the previous content and
// returns an error, so nginx is never left with a broken config.
func (c *Client) WriteAndApply(ctx context.Context, ports []int) error {
	previous, readErr := os.ReadFile(c.UpstreamPath)
	hadPrevious := readErr == nil

	content := Render(c.UpstreamName, c.StickySessions, ports)
	if err := os.MkdirAll(filepath.Dir(c.UpstreamPath), 0o755); err != nil {
		return fmt.Errorf("create nginx conf dir: %w", err)
	}
	if err := os.WriteFile(c.UpstreamPath, []byte(content), 0o644); err != nil {
		return fmt.Errorf("write nginx upstream file: %w", err)
	}

	if out, err := runShell(ctx, c.TestCmd); err != nil {
		// Roll back to the previous content so nginx is not left with a broken config.
		if hadPrevious {
			_ = os.WriteFile(c.UpstreamPath, previous, 0o644)
		}
		return fmt.Errorf("nginx config test failed, upstream file rolled back: %w (output: %s)", err, strings.TrimSpace(out))
	}

	if out, err := runShell(ctx, c.ReloadCmd); err != nil {
		return fmt.Errorf("nginx reload failed: %w (output: %s)", err, strings.TrimSpace(out))
	}
	return nil
}
